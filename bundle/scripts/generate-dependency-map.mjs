#!/usr/bin/env node
/**
 * Generates docs/agent/dependency-map.md — the "what breaks if I change this" lookup
 * required by AGENTS.md §7. Run via `npm run graph`.
 *
 * Grep answers "where is this text". This answers "who imports this file".
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const OUT = 'docs/agent/dependency-map.md';

// Surfaces where an unnoticed caller causes the most damage.
const HOT = [
  'packages/contracts',
  'packages/brain',
  'apps/api/src/db/schema.ts',
  'apps/api/src/app.ts',
  'apps/api/src/auth',
  'apps/api/src/llm',
  'apps/api/src/evidence',
  'apps/api/src/connectors',
  'apps/api/src/services',
];

const raw = execFileSync(
  'npx',
  ['--no-install', 'depcruise', 'apps', 'packages', '--output-type', 'json'],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
);

const { modules } = JSON.parse(raw);

// Invert the graph: file -> everything that imports it.
const importers = new Map();
for (const mod of modules) {
  for (const dep of mod.dependencies ?? []) {
    if (dep.resolved.includes('node_modules')) continue;
    if (!importers.has(dep.resolved)) importers.set(dep.resolved, []);
    importers.get(dep.resolved).push(mod.source);
  }
}

const isHot = (file) => HOT.some((prefix) => file.startsWith(prefix));
const workspaceOf = (file) => file.split('/').slice(0, 2).join('/');

const lines = [
  '# Dependency map',
  '',
  '**Generated by `npm run graph`. Do not edit.**',
  '',
  'Before changing anything listed here, read its importers and state the blast radius',
  '(AGENTS.md §7). A file with many importers across several workspaces is a cross-slice',
  'change — stop and ask.',
  '',
  `Generated: ${new Date().toISOString().slice(0, 10)} · ${modules.length} modules`,
  '',
  '## High-risk surfaces',
  '',
];

const hot = [...importers.entries()]
  .filter(([file]) => isHot(file))
  .sort((a, b) => b[1].length - a[1].length);

for (const [file, callers] of hot) {
  const spread = [...new Set(callers.map(workspaceOf))].sort();
  const risk = spread.length > 1 ? ' ⚠️ **crosses workspaces**' : '';
  lines.push(`### \`${file}\``);
  lines.push(`${callers.length} importer(s) across ${spread.join(', ')}${risk}`);
  lines.push('');
  for (const caller of [...new Set(callers)].sort()) lines.push(`- \`${caller}\``);
  lines.push('');
}

lines.push('## Most-depended-upon files overall', '');
const top = [...importers.entries()]
  .sort((a, b) => b[1].length - a[1].length)
  .slice(0, 25);
lines.push('| File | Importers | Workspaces |', '|---|---|---|');
for (const [file, callers] of top) {
  const spread = [...new Set(callers.map(workspaceOf))].sort().join(', ');
  lines.push(`| \`${file}\` | ${callers.length} | ${spread} |`);
}
lines.push('');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`${OUT} written — ${hot.length} high-risk surfaces, ${modules.length} modules`);
